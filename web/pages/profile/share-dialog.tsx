/** Address of a profile, the only one it has (§9) */
export const profileUrl = (login: Login) => `${location.origin}/@${login}`

const shareLinks = (login: Login) => {
  const link = encodeURIComponent(profileUrl(login))
  const text = encodeURIComponent(
    isMe(login)
      ? 'Mon profil Pamoja : mes reviews et contributions, vérifiées par GitHub.'
      : `Le profil Pamoja de ${people[login].name}`,
  )
  return [
    [
      'LinkedIn',
      `https://www.linkedin.com/sharing/share-offsite/?url=${link}`,
    ],
    ['X', `https://x.com/intent/post?url=${link}&text=${text}`],
    ['WhatsApp', `https://wa.me/?text=${text}%20${link}`],
  ]
}

/**
 * Preview of the share card, the profile Open Graph image (1200 × 630)
 * generated by the server with PAM-305. No decorative figure (§12.7).
 */
const Card = ({ login }: { login: Login }) => {
  const person = people[login]
  const mine = proofsOf(login)
  const top = badgesOf(login)
    .filter((badge) => badge.level >= 0)
    .sort((a, b) => b.level - a.level)[0]
  const stats = [
    [mine.filter((p) => p.dimension === 'review').length, 'reviews'],
    [mine.filter((p) => p.verified).length, 'preuves vérifiées'],
    [new Set(mine.map((p) => p.by).filter(Boolean)).size, 'collaborations'],
  ] as const
  return (
    <div class='@container grid aspect-[1200/630] w-full grid-cols-[1.5fr_1fr] overflow-hidden rounded-lg border border-figure-edge bg-surface-100 shadow-slab'>
      <div class='flex flex-col justify-center gap-[1.6cqw] px-[4cqw] py-[5cqw]'>
        <div class='flex items-center gap-[2cqw]'>
          <span class='flex size-[9cqw] flex-none items-center justify-center rounded-full border border-figure-edge bg-surface-200 font-display text-[3.2cqw] leading-none font-bold shadow-tile'>
            {initials(person.name)}
          </span>
          <span class='flex flex-col'>
            <span class='font-display text-[4cqw] leading-[1.1] font-bold'>
              {person.name}
            </span>
            <span class='text-[1.9cqw] text-ink-muted'>
              {person.city}, {person.country}
            </span>
          </span>
        </div>
        <span class='text-[2.3cqw] leading-[1.4] text-pretty'>
          {person.headline}
        </span>
        <div class='flex gap-[2.4cqw]'>
          {stats.map(([count, label]) => (
            <span key={label} class='flex flex-col'>
              <span class='font-mono text-[3.4cqw] leading-none font-medium'>
                {count}
              </span>
              <span class='text-[1.6cqw] text-ink-muted'>
                {label}
              </span>
            </span>
          ))}
        </div>
        <span class='self-start rounded-sm border border-verified bg-verified-soft px-[1.2cqw] py-[.6cqw] font-mono text-[1.5cqw] leading-none font-medium tracking-[.06em] text-verified uppercase'>
          {top ? `${top.name} · ${levelName(top)}` : 'Profil Pamoja'}
        </span>
      </div>
      <div class='flex flex-col items-center justify-center gap-[1.4cqw] border-l border-figure-edge bg-surface-000 p-[2cqw]'>
        <span class='flex items-center gap-[1cqw]'>
          <LogoMark size={22} />
          <span class='font-display text-[2.4cqw] leading-none font-bold'>
            Pamoja
          </span>
        </span>
        <span class='font-mono text-[1.5cqw] leading-none text-ink-muted'>
          {location.host}/@{login}
        </span>
      </div>
    </div>
  )
}

