// Generates web/assets/styles/theme.css from docs/identite/tokens.json:
// the color variables of both themes, the isometric reliefs and the Tailwind
// theme that exposes them as utilities (bg-surface-100, shadow-slab, ...)

type Themed = { light: string; dark: string }
type TypeStyle = {
  name: string
  fontSize: string
  lineHeight: string
  fontWeight: number
  letterSpacing?: string
}
type Tokens = {
  color: { tokens: { name: string; value: Themed }[] }
  type: {
    families: Record<string, string>
    groups: { styles: TypeStyle[] }[]
  }
  radius: { tokens: { name: string; value: string }[] }
  shadow: { tokens: { name: string; value: Themed }[] }
}

const tokens: Tokens = JSON.parse(
  Deno.readTextFileSync('docs/identite/tokens.json'),
)

const colors = tokens.color.tokens
const pop = tokens.shadow.tokens.find((t) => t.name === 'shadow-pop')
if (!pop) throw Error('shadow-pop: token required in tokens.json')

const themeVars = (theme: keyof Themed) =>
  [
    `  color-scheme: ${theme};`,
    ...colors.map((c) => `  --${c.name}: ${c.value[theme]};`),
    `  --pop: ${pop.value[theme]};`,
  ].join('\n')

// Thickness is drawn at 30°: each layer moves 0.866px right and 0.5px down.
// Layers start at the second step, faces first, then their 1px edges.
const relief = (steps: number, face: string, edge: string) => {
  const layers = Array.from({ length: steps - 1 }, (_, i) => {
    const k = i + 2
    return `${(0.866 * k).toFixed(2)}px ${(0.5 * k).toFixed(2)}px`
  })
  return [
    ...layers.map((at) => `${at} 0 0 var(--${face})`),
    ...layers.map((at) => `${at} 0 1px var(--${edge})`),
  ].join(', ')
}

// 8 steps = the 8px of a slab, 12 when it rises; keys are 4px, 5 on hover
const reliefs: Record<string, string> = {
  slab: relief(8, 'side', 'figure-edge'),
  'slab-hi': relief(12, 'side', 'figure-edge'),
  'slab-selected': relief(8, 'indigo-soft-side', 'indigo'),
  'slab-pop': `${relief(8, 'side', 'figure-edge')}, var(--pop)`,
  key: relief(4, 'side', 'line-control'),
  'key-hi': relief(5, 'side', 'line-control'),
  'key-primary': relief(4, 'indigo-side', 'indigo-edge'),
  'key-primary-hi': relief(5, 'indigo-side', 'indigo-edge'),
  'key-danger': relief(4, 'side', 'danger'),
  'key-danger-hi': relief(5, 'side', 'danger'),
  'key-selected': relief(3, 'indigo-soft-side', 'indigo'),
  tile: relief(3, 'side', 'figure-edge'),
}

const textStyles = tokens.type.groups.flatMap((g) => g.styles)

const css =
  `/* Generated by task-generate-theme.ts from docs/identite/tokens.json */
/* Do not edit: run \`deno task theme\` */

:root {
${themeVars('light')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${themeVars('dark')}
  }
}

:root[data-theme='dark'] {
${themeVars('dark')}
}

@theme {
  --color-*: initial;
  --font-*: initial;
  --text-*: initial;
  --shadow-*: initial;
  --inset-shadow-*: initial;
}

@theme inline {
${colors.map((c) => `  --color-${c.name}: var(--${c.name});`).join('\n')}

${
    Object.entries(tokens.type.families)
      .map(([name, family]) => `  --font-${name}: ${family};`)
      .join('\n')
  }

${
    textStyles.map((s) =>
      [
        `  --text-${s.name}: ${s.fontSize};`,
        `  --text-${s.name}--line-height: ${s.lineHeight};`,
        `  --text-${s.name}--font-weight: ${s.fontWeight};`,
        s.letterSpacing &&
        `  --text-${s.name}--letter-spacing: ${s.letterSpacing};`,
      ].filter(Boolean).join('\n')
    ).join('\n')
  }

${
    tokens.radius.tokens
      .filter((r) => r.name !== 'radius-full')
      .map((r) => `  --${r.name}: ${r.value};`)
      .join('\n')
  }

${
    Object.entries(reliefs)
      .map(([name, value]) => `  --shadow-${name}: ${value};`)
      .join('\n')
  }
  --inset-shadow-well: inset 1.73px 1px 0 0 var(--line), inset 3.46px 2px 0 0 var(--surface-200);
}
`

Deno.writeTextFileSync('web/assets/styles/theme.css', css)

// deno fmt takes care of the indentation
new Deno.Command('deno', { args: ['fmt', 'web/assets/styles/theme.css'] })
  .outputSync()
